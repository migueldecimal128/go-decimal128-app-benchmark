//go:build ignore

// gen writes width64.go and width128.go from width.go.tmpl: from its
// //go:build line on, DW becomes decimal64 or decimal128, and W, alone or at
// the end of an identifier (moneyW, benchOpsW), becomes 64 or 128.
package main

import (
	"bytes"
	"go/format"
	"os"
	"regexp"
)

var (
	suffix = regexp.MustCompile(`([A-Za-z])W\b`)
	alone  = regexp.MustCompile(`\bW\b`)
)

func main() {
	tmpl, err := os.ReadFile("width.go.tmpl")
	check(err)
	i := bytes.Index(tmpl, []byte("//go:build"))
	if i < 0 {
		panic("width.go.tmpl: no //go:build line")
	}
	body := tmpl[i:]
	for _, w := range []string{"64", "128"} {
		s := bytes.ReplaceAll(body, []byte("DW"), []byte("decimal"+w))
		s = suffix.ReplaceAll(s, []byte("${1}"+w))
		s = alone.ReplaceAll(s, []byte(w))
		out := append([]byte("// Code generated by gen.go from width.go.tmpl; DO NOT EDIT.\n\n"), s...)
		src, err := format.Source(out)
		check(err)
		check(os.WriteFile("width"+w+".go", src, 0o644))
	}
}

func check(err error) {
	if err != nil {
		panic(err)
	}
}
