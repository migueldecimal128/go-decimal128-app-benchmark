// loadRecords reads every record of one kind from results/data/<name>.jsonl.
func loadRecords[T any](root, name string) ([]T, error) {
	f, err := os.Open(filepath.Join(root, "results", "data", name+".jsonl"))
	if os.IsNotExist(err) {
		return nil, nil
	} else if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []T
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<24)
	for sc.Scan() {
		if strings.TrimSpace(sc.Text()) == "" {
			continue
		}
		var r T
		if err := json.Unmarshal(sc.Bytes(), &r); err != nil {
			return nil, fmt.Errorf("%s.jsonl: %w", name, err)
		}
		out = append(out, r)
	}
	return out, sc.Err()
}

func sub(r record) string {
	if r.Sub == nil {
		return ""
	}
	return *r.Sub
}

// writeReport writes results/RESULTS.md from the latest record per
// (arch, app, sub, library).
func writeReport(root string) error {
	latest := map[string]record{}
	for _, app := range appOrder {
		recs, err := loadRecords[record](root, app)
		if err != nil {
			return err
		}
		for _, r := range recs {
			k := strings.Join([]string{r.Arch, r.App, sub(r), r.Impl}, "|")
			if old, ok := latest[k]; !ok || (r.TimestampUTC > old.TimestampUTC) ||
				((r.TimestampUTC == old.TimestampUTC) && (r.WrittenUTC > old.WrittenUTC)) {
				latest[k] = r
			}
		}
	}
	starts, err := loadRecords[startupRecord](root, "startup")
	if err != nil {
		return err
	}
	startup := map[string]startupRecord{} // latest per arch
	for _, s := range starts {
		if old, ok := startup[s.Arch]; !ok || (s.TimestampUTC > old.TimestampUTC) {
			startup[s.Arch] = s
		}
	}

	byArch := map[string][]record{}
	for _, r := range latest {
		byArch[r.Arch] = append(byArch[r.Arch], r)
	}

	var b strings.Builder
	b.WriteString("# Results\n\n")
	b.WriteString("Generated by `go run ./cmd/bench -lib <libraries>` from `results/data/*.jsonl`: the latest record per app, form and library. Units: ns per record.\n\n")
	b.WriteString("- **compute** is the program's own timed loop (arithmetic and in-memory formatting of the output; no file I/O, no input decoding). It is the fastest sample over 3 processes, and the ranking key.\n")
	b.WriteString("- **median** and **p10–p90** cover the second half of each process's samples (the first half counts as warm-up). A wide range means the value is not stable.\n")
	b.WriteString("- **xcheck** is the runner's own clock divided by **compute**: it times a run with twice the samples and divides the extra wall time by the extra passes. Near 1.00 means the program's timer agrees; ⚠ marks a ratio outside 0.90–1.25 (banking 0.90–2.50, because it rebuilds its accounts between passes outside the timed loop).\n")
	b.WriteString("- **whole** is one gated run from process start to exit, fastest of N, after one untimed warm-up run (a newly built program's first launch is much slower). **startup** is a do-nothing Go program launched the same way, between the whole runs, so whole − startup is the program's own work.\n")
	b.WriteString("- **correct**: ✓ = every gated run matched the golden byte for byte; *n*/*m* = output files matched (risk); ✗ = a mismatch in at least one run.\n\n")

	for _, arch := range sortedKeys(byArch) {
		rows := byArch[arch]
		sort.Slice(rows, func(i, j int) bool {
			ai, aj := appIndex(rows[i].App), appIndex(rows[j].App)
			if ai != aj {
				return ai < aj
			}
			if sub(rows[i]) != sub(rows[j]) {
				return subIndex(sub(rows[i])) < subIndex(sub(rows[j]))
			}
			return computeKey(rows[i]) < computeKey(rows[j])
		})
		st, hasStart := startup[arch]
		fmt.Fprintf(&b, "## %s\n\n", arch)
		fmt.Fprintf(&b, "%s · %s · %s · benchmark code %s\n\n", rows[0].CPU, rows[0].GoVersion, runStamps(rows), benchCommits(rows))
		if hasStart {
			fmt.Fprintf(&b, "Startup baseline: **%.2f ms** (fastest of %d launches between the whole runs, measured %s).\n\n",
				float64(st.StartupNs)/1e6, st.Iterations, stamp(st.TimestampUTC))
		}
		b.WriteString("| app | library | compute | median | p10–p90 | xcheck | whole | startup | correct |\n")
		b.WriteString("|---|---|--:|--:|--:|--:|--:|--:|:--:|\n")
		var notes []string
		for _, r := range rows {
			name := r.App
			if s := sub(r); s != "" {
				name += " " + s
			}
			lib := r.Impl + " `" + shortVersion(r.LibraryVersion) + "`"
			comp, med, rng, xc := "FAILED", "—", "—", "—"
			if r.ComputeStatus == "ok" && r.ComputeNsPerRecord != nil {
				comp = num(*r.ComputeNsPerRecord, 1)
				med = num(*r.ComputeMedian, 1)
				rng = num(*r.ComputeP10, 1) + "–" + num(*r.ComputeP90, 1)
				if r.XcheckRatio != nil {
					xc = fmt.Sprintf("%.2f", *r.XcheckRatio)
					if *r.XcheckFlag {
						xc += " ⚠"
					}
				}
			} else if r.ComputeStatus == "failed" {
				notes = append(notes, fmt.Sprintf("FAILED %s: %s", name, r.ComputeError))
			}
			if r.ComputeStatus == "unsupported" {
				fmt.Fprintf(&b, "| %s | %s | not supported | — | — | — | — | — | — |\n", name, lib)
				notes = append(notes, fmt.Sprintf("%s does not run %s: %s.", r.Impl, name, r.ComputeError))
				continue
			}
			startCell := "—"
			if hasStart {
				startCell = num(float64(st.StartupNs)/float64(r.Records), 1)
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
				name, lib, comp, med, rng, xc, num(r.WholeNsPerRecord, 1), startCell, correctCell(r))
		}
		b.WriteString("\n")
		for _, n := range notes {
			fmt.Fprintf(&b, "> %s\n", n)
		}
		if len(notes) > 0 {
			b.WriteString("\n")
		}
		var libsSeen []string
		seenLib := map[string]bool{}
		for _, r := range rows {
			if !seenLib[r.Impl] {
				seenLib[r.Impl] = true
				libsSeen = append(libsSeen, r.Impl)
			}
		}
		b.WriteString("Libraries:\n\n")
		for _, l := range libsSeen {
			fmt.Fprintf(&b, "- **%s**: %s\n", l, libraryNote[l])
		}
		b.WriteString("\n")
		b.WriteString("Workloads:\n\n")
		for _, app := range appOrder {
			fmt.Fprintf(&b, "- **%s**: %s\n", app, appMeta[app])
		}
		b.WriteString("\n")
	}
	return os.WriteFile(filepath.Join(root, "results", "RESULTS.md"), []byte(b.String()), 0o644)
}

func appIndex(app string) int {
	for i, a := range appOrder {
		if a == app {
			return i
		}
	}
	return len(appOrder)
}

func subIndex(s string) int {
	return strings.Index("|fed|ca|nc|", "|"+s+"|")
}

func computeKey(r record) float64 {
	if r.ComputeNsPerRecord == nil {
		return math.Inf(1)
	}
	return *r.ComputeNsPerRecord
}

func correctCell(r record) string {
	if (r.GoldenPassed != nil) && (r.GoldenTotal != nil) {
		return fmt.Sprintf("%d/%d", *r.GoldenPassed, *r.GoldenTotal)
	}
	if r.Correct {
		return "✓"
	}
	return "✗"
}

// runStamps says whether the rows come from one run or several.
func runStamps(rows []record) string {
	seen := map[string]bool{}
	for _, r := range rows {
		seen[r.TimestampUTC] = true
	}
	if len(seen) == 1 {
		return "all rows measured in one run, " + stamp(rows[0].TimestampUTC)
	}
	ts := sortedKeys(seen)
	return fmt.Sprintf("rows from %d runs, %s to %s", len(ts), stamp(ts[0]), stamp(ts[len(ts)-1]))
}

// benchCommits names the benchmark code the rows were measured with.
func benchCommits(rows []record) string {
	seen := map[string]bool{}
	for _, r := range rows {
		c := r.BenchCommit
		if c == "" {
			c = "unrecorded"
		} else if len(c) > 7 {
			c = c[:7]
		}
		if r.BenchDirty {
			c += " + uncommitted changes"
		}
		seen["`"+c+"`"] = true
	}
	return strings.Join(sortedKeys(seen), ", ")
}

func stamp(ts string) string {
	t, err := time.Parse("2006-01-02T15:04:05.000Z", ts)
	if err != nil {
		return ts
	}
	return t.Format("2006-01-02 15:04 UTC")
}

// shortVersion turns a pseudo-version into its commit (v0.0.0-<date>-<commit>).
func shortVersion(v string) string {
	if i := strings.LastIndex(v, "-"); (i >= 0) && (len(v)-i-1 == 12) {
		return v[i+1 : i+8]
	}
	return v
}

// num formats v with thousands separators.
func num(v float64, decimals int) string {
	s := fmt.Sprintf("%.*f", decimals, v)
	intPart, frac := s, ""
	if i := strings.IndexByte(s, '.'); i >= 0 {
		intPart, frac = s[:i], s[i:]
	}
	neg := strings.HasPrefix(intPart, "-")
	if neg {
		intPart = intPart[1:]
	}
	var out []byte
	for i := range intPart {
		if (i > 0) && ((len(intPart)-i)%3 == 0) {
			out = append(out, ',')
		}
		out = append(out, intPart[i])
	}
	if neg {
		return "-" + string(out) + frac
	}
	return string(out) + frac
}
